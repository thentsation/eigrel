def spark_code(source: str) -> str:
    return generate(compile_source(source), 'test.eig')


def test_header_and_session() -> None:
    code = spark_code('dataset d from csv("d.csv")')
    assert code.startswith('"""Generated by eigrel ')
    assert 'from test.eig for Apache Spark. Do not edit."""' in code
    assert "spark = SparkSession.builder.appName('eigrel: test.eig').getOrCreate()" in code
    assert "os.environ.setdefault('PYSPARK_PYTHON', sys.executable)" in code
    assert 'spark.jars.packages' not in code
    assert code.endswith('spark.stop()\n')


