def test_filters_and_select() -> None:
    code = spark_code(
        'dataset d from csv("d.csv")\n'
        'transform d { filter not (a > -1) or b == "x" and c != true\n select a, b }'
    )
    assert (
        "d = d.filter((~((F.col('a') > -(F.lit(1)))) | ((F.col('b') == F.lit('x'))"
        " & (F.col('c') != F.lit(True)))))"
    ) in code
    assert "d = d.select('a', 'b')" in code


