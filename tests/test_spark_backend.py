def jdbc(url: str, table: str = 't') -> tuple[dict[str, str], str]:
    namespace: dict[str, object] = {
        'JDBC_DRIVERS': JDBC_DRIVERS,
        'urlsplit': urlsplit,
        'unquote': unquote,
    }
    exec(JDBC_HELPER, namespace)  # noqa: S102 - the helper ships inside generated scripts
    return namespace['jdbc_options'](url, table)  # type: ignore[operator, no-any-return]


def test_jdbc_options_from_sqlalchemy_urls() -> None:
    options, package = jdbc('postgresql+psycopg://ana:p%40ss@db.example.com:5433/shop', 's.t')
    assert options == {
        'url': 'jdbc:postgresql://db.example.com:5433/shop',
        'dbtable': 's.t',
        'driver': 'org.postgresql.Driver',
        'user': 'ana',
        'password': 'p@ss',
    }
    assert package.startswith('org.postgresql:postgresql:')
    assert jdbc('mysql://h/db')[0]['url'] == 'jdbc:mysql://h/db'
    assert jdbc('mariadb+pymysql://h:3307/db')[0]['url'] == 'jdbc:mariadb://h:3307/db'
    assert jdbc('sqlite:///data/shop.db')[0]['url'] == 'jdbc:sqlite:data/shop.db'
    assert jdbc('sqlite:////abs/shop.db')[0]['url'] == 'jdbc:sqlite:/abs/shop.db'
    with pytest.raises(SystemExit, match='Spark cannot read oracle databases yet'):
        jdbc('oracle://h/db')


def run_on_spark(program: Path) -> str:
    code = generate(compile_source(program.read_text()), program.name)
    result = subprocess.run(
        [sys.executable, '-c', code],
        cwd=program.parent,
        capture_output=True,
        text=True,
        check=True,
        env={**os.environ, 'PYSPARK_PYTHON': sys.executable},
        timeout=600,
    )
    return result.stdout


@pytest.mark.spark
def test_classification_runs_on_spark(examples_dir: Path) -> None:
    out = run_on_spark(examples_dir / 'ml.eig')
    assert re.search(r'churn: random_forest classification, trained on \d+ rows', out)
    assert re.search(r'  f1         0\.\d{4}', out)


